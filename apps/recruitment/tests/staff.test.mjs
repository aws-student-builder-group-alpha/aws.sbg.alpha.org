import test from "node:test";
import assert from "node:assert/strict";
import { validateStaffRequest, membershipFromRow, isStaffMember, isStaffHistory } from "../lib/staff.ts";
import { authenticatorQrDataUrl, MAX_AUTHENTICATOR_QR_LENGTH } from "../lib/authenticator.ts";
import { denseAuthenticatorSvg } from "./fixtures/authenticator.mjs";

const request = () => ({ action: "grant", email: "staff@example.test", targetId: "", role: "evaluator", expectedVersion: 0, mutationId: crypto.randomUUID(), reason: "Approved recruitment responsibility" });
test("staff commands use bounded reasons, known roles/actions, revisions, and operation IDs", () => {
  assert.equal(validateStaffRequest(request()), true);
  for (const patch of [{ role: "owner" }, { action: "delete_user" }, { reason: " " }, { reason: "x".repeat(501) }, { expectedVersion: 1 }, { mutationId: "invalid" }, { email: "not-an-email" }, { actorId: crypto.randomUUID() }]) assert.equal(validateStaffRequest({ ...request(), ...patch }), false);
  assert.equal(validateStaffRequest({ ...request(), action: "suspend", email: "", targetId: crypto.randomUUID(), expectedVersion: 2 }), true);
  assert.equal(validateStaffRequest({ ...request(), action: "suspend", targetId: crypto.randomUUID(), expectedVersion: 2 }), false);
});
test("membership and administrator DTOs reject invalid identities, roles, statuses, and versions", () => {
  const value = { user_id: crypto.randomUUID(), role: "administrator", status: "active", version: 1 };
  assert.equal(membershipFromRow(value).role, "administrator");
  for (const patch of [{ role: "owner" }, { status: "deleted" }, { version: 0 }, { user_id: "invalid" }]) assert.equal(membershipFromRow({ ...value, ...patch }), null);
  const dto = { userId: value.user_id, role: value.role, status: value.status, version: 1, email: "staff@example.test", createdAt: "2026-10-19T00:00:00Z", updatedAt: "2026-10-19T00:00:00Z" };
  assert.equal(isStaffMember(dto), true);
  assert.equal(isStaffMember({ ...dto, userId: "invalid", user_id: value.user_id }), false);
});
test("history DTOs permit owner bootstrap without inventing an application actor", () => {
  const value = { id: crypto.randomUUID(), actorId: null, actorEmail: null, action: "bootstrap", previousRole: null, previousStatus: null, newRole: "administrator", newStatus: "active", reason: "Owner setup", targetVersion: 1, createdAt: "2026-10-19T00:00:00Z" };
  assert.equal(isStaffHistory(value), true);
  assert.equal(isStaffHistory({ ...value, action: "grant_owner" }), false);
  assert.equal(isStaffHistory({ ...value, newStatus: "deleted" }), false);
});
test("authenticator QR images normalize SDK data URIs without double encoding or color fragments", () => {
  const svg = '<svg xmlns="http://www.w3.org/2000/svg"><path fill="#000" d="M0 0"/></svg>';
  const uri = authenticatorQrDataUrl("data:image/svg+xml;utf-8," + svg);
  assert.equal(decodeURIComponent(uri.split(",")[1]), svg);
  assert.equal(uri.includes("#"), false);
  assert.equal(authenticatorQrDataUrl(svg), uri);
  assert.equal(authenticatorQrDataUrl("https://example.test/qr.svg"), null);
  assert.equal(authenticatorQrDataUrl(null), null);
});

test("authenticator QR images accept Supabase XML declarations and generator comments", () => {
  const svg = '<svg xmlns="http://www.w3.org/2000/svg" width="220" height="220"><path fill="#000" d="M0 0"/></svg>';
  const document = '<?xml version="1.0"?>\n<!-- Generated by SVGo -->\n' + svg;
  const expected = "data:image/svg+xml;charset=utf-8," + encodeURIComponent(svg);
  for (const source of [svg, document, "\uFEFF \n" + document, "<!-- First -->\n<!-- Second -->\n" + svg]) {
    assert.equal(authenticatorQrDataUrl(source), expected);
    assert.equal(authenticatorQrDataUrl("data:image/svg+xml;utf-8," + source), expected);
  }
});

test("authenticator QR images reject malformed headers, non-SVG roots, and oversized input", () => {
  for (const value of [
    undefined, null, 42, {}, "", "https://example.test/qr.svg",
    "data:text/html,<svg></svg>", "<html><svg></svg></html>", "<svg-script></svg-script>",
    '<?xml version="1.0"<svg></svg>', "<!-- Unclosed <svg></svg>",
    '<?xml version="1.0"?><!-- Unclosed <svg></svg>',
    '<?xml-stylesheet href="external.css"?><svg></svg>',
    "<svg>" + " ".repeat(MAX_AUTHENTICATOR_QR_LENGTH) + "</svg>",
  ]) assert.equal(authenticatorQrDataUrl(value), null);
});

test("authenticator QR images accept realistic dense provider SVGs exceeding the former cap", () => {
  const svg = denseAuthenticatorSvg();
  assert.ok(svg.length > 100000);
  const uri = authenticatorQrDataUrl("data:image/svg+xml;utf-8," + svg);
  assert.ok(uri);
  assert.equal(decodeURIComponent(uri.split(",")[1]), svg.slice(svg.indexOf("<svg")));
});

test("authenticator QR input is bounded at one MiB including the SDK prefix", () => {
  const prefix = "data:image/svg+xml;utf-8,";
  const padding = MAX_AUTHENTICATOR_QR_LENGTH - prefix.length - "<svg></svg>".length;
  const boundary = prefix + "<svg>" + " ".repeat(padding) + "</svg>";
  assert.equal(boundary.length, 1024 * 1024);
  assert.ok(authenticatorQrDataUrl(boundary));
  assert.equal(authenticatorQrDataUrl(boundary + " "), null);
});

test("QR rejection diagnostics contain only length and category without setup material", () => {
  const diagnostics = [];
  const value = "synthetic-private-setup-material";
  assert.equal(authenticatorQrDataUrl(value, diagnostic => diagnostics.push(diagnostic)), null);
  assert.deepEqual(diagnostics, [{ inputLength: value.length, reason: "invalid_svg" }]);
  assert.equal(JSON.stringify(diagnostics).includes(value), false);
  assert.equal(authenticatorQrDataUrl("<svg>\uD800</svg>", diagnostic => diagnostics.push(diagnostic)), null);
  assert.deepEqual(diagnostics[1], { inputLength: 12, reason: "invalid_encoding" });
});
